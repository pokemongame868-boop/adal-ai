-- ADAL AI — Supabase schema (MVP)
-- Apply once in Supabase Dashboard → SQL Editor → New query → paste → Run.
-- Safe to re-run (idempotent).
--
-- Scope: ONLY anonymous product feedback / improvement suggestions.
-- Deliberately NOT stored: AI conversations, complaint drafts, corruption allegations, quiz progress,
-- IP addresses, user agents. Quiz and educational content stay static in the app.

create extension if not exists pgcrypto;

create table if not exists public.feedback (
  id            uuid        primary key default gen_random_uuid(),
  created_at    timestamptz not null    default now(),
  category      text        not null check (category in ('idea', 'ux', 'content', 'bug', 'other')),
  message       text        not null check (char_length(btrim(message)) between 10 and 1000),
  -- Optional, only if the visitor wants a reply.
  contact_email text                    check (contact_email is null or (char_length(contact_email) <= 200 and contact_email ~* '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]{2,}$')),
  lang          text        not null check (lang in ('ru', 'kk')),
  -- Defence in depth: reject 12-digit IIN-like and 16-digit card-like numbers (same rule as the app).
  constraint feedback_no_iin_or_card check (
    message !~ '(^|[^0-9])[0-9]{12}([^0-9]|$)'
    and message !~ '(^|[^0-9])([0-9][ -]?){15}[0-9]([^0-9]|$)'
  )
);

create index if not exists feedback_created_at_idx on public.feedback (created_at desc);

-- Row Level Security: anonymous/authenticated API roles may INSERT only. No SELECT/UPDATE/DELETE
-- policies exist, so feedback cannot be read or changed through the public (anon/publishable) key.
-- Read it in the Supabase Dashboard (Table Editor) or with the service role, which bypasses RLS.
alter table public.feedback enable row level security;

drop policy if exists "feedback_insert_only" on public.feedback;
create policy "feedback_insert_only"
  on public.feedback
  for insert
  to anon, authenticated
  with check (true);  -- content rules are enforced by the CHECK constraints above

-- Table privileges: strip defaults, then allow inserting only the user-supplied columns
-- (id and created_at are always generated by the database).
revoke all on table public.feedback from anon, authenticated;
grant insert (category, message, contact_email, lang) on table public.feedback to anon, authenticated;

