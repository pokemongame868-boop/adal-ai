/**
 * DEMO MODE ONLY. Static, pre-written fictional guidance used when no AI API is configured.
 * These responses are always returned with `demo: true` and labelled in the UI as not AI-generated.
 */
type Topic = 'education' | 'service' | 'complaint' | 'general';

function topicOf(text: string): Topic {
  const t = text.toLowerCase();
  if (/(университет|универ|колледж|школ|оценк|экзамен|сессия|преподав|баға|емтихан|оқытушы|мұғалім|мектеп|сынақ)/.test(t)) return 'education';
  if (/(обращени|жалоб|составить|өтініш|шағым|арыз)/.test(t)) return 'complaint';
  if (/(услуг|цон|госорган|справк|акимат|қызмет|хқко|әкімдік|анықтама)/.test(t)) return 'service';
  return 'general';
}

